package ru.mirea.danilov.recyclerviewapp;

public class Event {
    public final int year;
    public final String title;
    public final String text;
    public final int color;

    public Event(int year, String title, String text, int color) {
        this.year = year;
        this.title = title;
        this.text = text;
        this.color = color;
    }
}
